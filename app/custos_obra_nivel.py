MAPA = {conta: cat for cat, contas in CONTAS_POR_CATEGORIA.items() for conta in contas}
CONTAS = tuple(MAPA)


def contas_das_categorias(codigos) -> set:
    """Contas do plano das categorias marcadas na tabela. Marcar uma categoria de nivel 1 ('01') inclui as subcategorias ('01.01'...); '00' (custo total) = todas as contas."""
    cods = set(codigos or ())
    if "00" in cods:
        return set(MAPA)
    return {conta for conta, cat in MAPA.items() if cat in cods or cat.split(".")[0] in cods}


def por_categoria(linhas, obras=None, destino=None, mes=None) -> dict:
    """Soma o custo (positivo = gasto) por categoria de NIVEL 2 e por nivel 1.
    `linhas` = [(obra, 'AAAA-MM', plano_cod, resultado)] (resultado: custo negativo, como no DRE). `destino(obra)` leva a obra do banco para a linha da tabela de Obras
    ('DEM' para as que ficam em "Demais obras"); `obras` = linhas marcadas na tabela (vazio/None = todas); `mes` = so' esse mes (None = o periodo todo).
    -> {'01.01': 123.0, '01': 123.0, ..., '00': total}"""
    alvo = set(obras) if obras else None
    nivel2 = {}
    for obra, m, conta, v in linhas:
        cat = MAPA.get(conta)
        if cat is None or (mes is not None and m != mes):
            continue
        dest = destino(obra) if destino else obra
        if alvo is not None and dest not in alvo:
            continue
        nivel2[cat] = nivel2.get(cat, 0.0) - float(v or 0)
    out = dict(nivel2)
    for cod, _ in CATEGORIAS:
        if cod != "00" and "." not in cod:
            out[cod] = sum(x for c, x in nivel2.items() if c.startswith(cod + "."))
    out["00"] = sum(x for c, x in out.items() if "." not in c and c != "00")
    return {k: round(v, 2) for k, v in out.items()}


def tabela(linhas, obras=None, destino=None, mes=None) -> list:
    """Linhas da tabela: [{'codigo','categoria','periodo','mes','pct'}] na ordem do relatorio; categorias de nivel 2 sem nenhum valor saem (as de nivel 1 ficam)."""
    per = por_categoria(linhas, obras, destino)
    mm = por_categoria(linhas, obras, destino, mes=mes) if mes else {}
    tot = per.get("00", 0.0)
    out = []
    for cod, nome in CATEGORIAS:
        v = per.get(cod, 0.0)
        if "." in cod and abs(v) < 0.005 and abs(mm.get(cod, 0.0)) < 0.005:
            continue
        out.append({"codigo": cod, "categoria": nome, "periodo": v, "mes": mm.get(cod, 0.0), "pct": (v / tot) if abs(tot) > 0.005 else None})
    return out
